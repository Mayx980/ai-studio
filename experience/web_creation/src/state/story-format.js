export const directionFields = [
  ['purpose', '制作目的', '例如产品宣传、活动预热或故事短片'],
  ['style', '风格', '描述希望的视觉与叙事风格'],
  ['duration', '时长', '例如30秒'],
  ['ratio', '画面比例', '例如16:9或9:16'],
  ['content', '核心内容', '主角、产品、事件或必须表达的信息'],
  ['audience', '目标受众', '这段视频希望让谁看到']
]
export function inferDirection(text) {
  const find = pattern => text.match(pattern)?.[1]?.trim() || ''
  return {
    purpose:
      find(/(?:目的|用途)[：:]([^\n；;]+)/) ||
      find(/(产品宣传|活动预热|品牌宣传|故事短片|教学演示|广告)/),
    style:
      find(/(?:风格)[：:]?([^\n；;]+)/) || find(/(写实|电影感|动画|温暖治愈|极简|赛博朋克|纪录片)/),
    duration: find(/(\d+\s*(?:秒|分钟|s\b))/i),
    ratio: find(/(\d+\s*[:：]\s*\d+)/),
    content:
      find(/(?:核心内容|内容|主题)[：:]([^\n；;]+)/) ||
      find(/(?:制作|创作|拍摄)([^\n；;。]{3,60})/),
    audience: find(/(?:目标受众|受众|面向)[：:]?([^\n；;]+)/)
  }
}
